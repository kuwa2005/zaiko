function markLog(string $when): void
{
    global $__lastLog;
    db_exec("UPDATE 操作ログ SET 操作日時 = ? WHERE id > ?", [$when, $__lastLog]);
    $__lastLog = (int)db_val("SELECT COALESCE(MAX(id),0) FROM 操作ログ");
}

function dt(string $day, string $time): string
{
    return $day . ' ' . $time;
}

function addItem(array $it): void
{
    item_register([
        'コード' => $it['コード'], '品名' => $it['品名'], '基本数量' => 1, '単位' => $it['単位'],
        '単価' => $it['単価'], '残数量' => 0, '安全在庫数' => $it['安全'], '最小発注数量' => $it['最小'],
        '適正在庫数' => $it['適在'],
        '標準納入日数' => $it['納入'], '棚番' => $it['棚番'], '取引先' => $it['取引先'],
    ], $it['登録者']);
    db_exec("UPDATE 在庫マスタ SET 登録日 = ?, 更新日 = ? WHERE コード = ?", [$it['登録日'], $it['登録日'], $it['コード']]);
    markLog(dt($it['登録日'], '09:0' . $it['no'] . ':00'));
}

function addOrder(string $code, float $qty, string $納期, string $依頼者, string $依頼日, string $備考 = ''): array
{
    draft_add(['コード' => $code, '数量' => $qty, '納期' => $納期, '備考' => $備考], $依頼者);
    drafts_commit($依頼者);
    $row = db_one("SELECT id, 管理NO FROM 発注データ WHERE 削除フラグ = 0 ORDER BY id DESC LIMIT 1");
    db_exec("UPDATE 発注データ SET 依頼日 = ?, created_at = ?, 更新日 = ? WHERE id = ?",
        [$依頼日, dt($依頼日, '10:00:00'), dt($依頼日, '10:00:00'), (int)$row['id']]);
    markLog(dt($依頼日, '10:00:00'));
    return [(int)$row['id'], (string)$row['管理NO']];
}

function doReceive(int $id, string $受付者, string $受付日): void
{
    receive_process([$id => '出力'], $受付者);
    db_exec("UPDATE 発注データ SET 受付日 = ?, 更新日 = ? WHERE id = ?", [$受付日, dt($受付日, '11:00:00'), $id]);
    markLog(dt($受付日, '11:00:00'));
}

function doInbound(int $id, string $入庫者, string $入庫日): void
{
    inbound_save([$id => '入庫'], $入庫者);
    db_exec("UPDATE 発注データ SET 入庫日 = ?, 更新日 = ? WHERE id = ?", [$入庫日, dt($入庫日, '14:00:00'), $id]);
    markLog(dt($入庫日, '14:00:00'));
}

function doShip(string $code, float $qty, string $出庫者, string $出庫日, string $出庫先 = ''): void
{
    outbound_register(['コード' => $code, '出庫数' => $qty, '出庫先' => $出庫先], $出庫者);
    $row = db_one("SELECT id FROM 出庫データ WHERE 削除フラグ = 0 ORDER BY id DESC LIMIT 1");
    db_exec("UPDATE 出庫データ SET 出庫日 = ?, created_at = ?, 更新日 = ? WHERE id = ?",
        [$出庫日, dt($出庫日, '09:30:00'), dt($出庫日, '09:30:00'), (int)$row['id']]);
    markLog(dt($出庫日, '09:30:00'));
}

